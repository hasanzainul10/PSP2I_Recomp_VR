#!/usr/bin/env python3
"""Differential test of the recompiler's inline VFPU code against the runtime.

usage: vfpu_diff.py OLD_GEN_C NEW_GEN_C OUTDIR [--trials N] [--cc cl|gcc]

OLD_GEN_C is a recomp_funcs.c from before the change (guarded by
psp_vfpu_pfx_any), NEW_GEN_C the same game recompiled after it (guarded by
PSP_VFPU_NOPFX, with more operations inline). The two files line up one to
one after the new one's extra #include. Every VFPU statement that is inline
in the new file -- old inline forms included -- is paired with the old
statement at the same place, and both are compiled into one test:

  reference: the old statement with psp_vfpu_force_runtime(1), so it always
             takes the runtime path (prefixes and all: src/vfpu.c);
  candidate: the new statement with PSP_VFPU_NOPFX defined as 1, so it always
             takes the inline path, as a -DPSPRECOMP_VFPU_UNGUARDED build does.

Each pair runs on N random register files (NaN, signed zero, infinity,
denormals, integers, ordinary floats) and the 128 vector registers, the 32
GPRs and the VFPU condition codes must match bit for bit.

The generated test holds code derived from the game, so it is written to
OUTDIR (keep that out of the repository) and never committed. Run it from a
shell with the compiler on PATH (vcvars64.bat for cl). Links against the
runtime library, by default psprecomp/build/Release/psprecomp.lib.
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))


def pairs(old_path, new_path):
    with open(old_path, 'r', encoding='utf-8', newline='') as f:
        old = f.read().replace('\r', '').split('\n')
    with open(new_path, 'r', encoding='utf-8', newline='') as f:
        new = f.read().replace('\r', '').split('\n')
    is_inc = lambda l: l.startswith('#include "') and l.endswith('_vfpu.h"')
    inc = next(i for i, l in enumerate(new) if is_inc(l))
    shift = 0 if any(is_inc(l) for l in old[:inc + 1]) else 1   # an old file from before the include
    if len(new) != len(old) + shift:
        sys.exit('vfpu_diff: the files do not line up (%d vs %d lines)' % (len(old), len(new)))
    seen, out = set(), []
    for i, o in enumerate(old):
        n = new[i + shift] if i >= inc else new[i]
        if i < inc and o != n:
            sys.exit('vfpu_diff: line %d differs before the include' % (i + 1))
        # the reference always takes the runtime path, so an old inline form
        # gets the run-time guard back (the test defines PSP_VFPU_NOPFX as 1)
        so, sn = o.strip().replace('PSP_VFPU_NOPFX', '(!psp_vfpu_pfx_any)'), n.strip()
        if so.startswith('/*') or 'psp_read' in sn or 'psp_write' in sn:
            continue
        if not ('PSP_VFPU_NOPFX' in sn or 'psp_mtv(' in so or 'psp_mfv(' in so):
            if so != sn:
                sys.exit('vfpu_diff: line %d changed outside the VFPU code:\n  %s\n  %s' % (i + 1, so, sn))
            continue
        key = (so, sn)
        if key not in seen:
            seen.add(key)
            out.append(key)
    return out


PROLOGUE = r'''/* Generated by port/3ds/tools/vfpu_diff.py -- holds code derived from the game. */
#include "recomp_funcs.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define PSP_VFPU_NOPFX 1
'''

MAIN = r'''
static uint64_t g_seed = 0x9E3779B97F4A7C15ull;
static uint32_t rnd(void) {
    g_seed ^= g_seed << 13; g_seed ^= g_seed >> 7; g_seed ^= g_seed << 17;
    return (uint32_t)(g_seed >> 16);
}
static uint32_t value(void) {
    static const uint32_t SPECIAL[] = { 0x00000000u, 0x80000000u, 0x7F800000u, 0xFF800000u, 0x7FC00000u,
        0x7F800001u, 0xFFC00001u, 0x00000001u, 0x80000001u, 0x007FFFFFu, 0x7F7FFFFFu, 0xFF7FFFFFu,
        0x3F800000u, 0xBF800000u, 0x3F000000u, 0x4B000000u, 0xCF000000u, 0x4F000000u, 0x7FFFFFFFu, 0xFFFFFFFFu };
    const uint32_t k = rnd() % 10;
    if (k < 3) return rnd();                                                 /* any bits */
    if (k < 5) return (uint32_t)((int32_t)(rnd() % 2001) - 1000);            /* small integers */
    if (k < 6) return rnd() & 0x0000FFFFu;                                   /* packed halves and bytes */
    if (k < 8) { float x = (float)((int32_t)(rnd() % 20001) - 10000) / 1250.0f; uint32_t b; memcpy(&b, &x, 4); return b; }
    return SPECIAL[rnd() % (sizeof SPECIAL / sizeof SPECIAL[0])];
}
static void randomize(void) {
    for (int i = 0; i < 128; i++) { const uint32_t b = value(); memcpy(&psp_cpu.v[i], &b, 4); }
    for (int i = 1; i < 32; i++) psp_cpu.r[i] = value();
    psp_cpu.r[0] = 0;
    psp_cpu.vfpu_cc = rnd() & 0x3F;
}
/* Bits equal, or both NaN: which NaN payload x64 propagates depends on the
 * operand order the compiler picked, which differs between the runtime and
 * the inline code (and the PSP's own NaN rules aren't modelled). Those are
 * counted apart in *nan_only. */
static int same_v(const psp_cpu_state *a, const psp_cpu_state *b, int strict, int *nan_only) {
    int nan = 0;
    for (int i = 0; i < 128; i++) {
        uint32_t x, y;
        memcpy(&x, &a->v[i], 4); memcpy(&y, &b->v[i], 4);
        if (x == y) continue;
        if (!strict && (x & 0x7FFFFFFFu) > 0x7F800000u && (y & 0x7FFFFFFFu) > 0x7F800000u) { nan = 1; continue; }
        return 0;
    }
    *nan_only += nan;
    return 1;
}
int main(int argc, char **argv) {
    const int trials = argc > 1 ? atoi(argv[1]) : 200;
    int bad = 0, nan_only = 0;
    psp_cpu_state a, b, start;
    for (int k = 0; k < NPAIRS; k++) {
        for (int t = 0; t < trials; t++) {
            randomize();
            start = psp_cpu;
            psp_vfpu_consume();
            psp_vfpu_force_runtime(1);
            REF[k]();
            psp_vfpu_force_runtime(0);
            psp_vfpu_consume();
            a = psp_cpu;
            psp_cpu = start;
            CAND[k]();
            b = psp_cpu;
            if (!same_v(&a, &b, STRICT[k], &nan_only) || memcmp(a.r, b.r, sizeof a.r) || a.vfpu_cc != b.vfpu_cc) {
                if (bad < 20) {
                    printf("MISMATCH pair %d trial %d\n  ref:  %s\n  cand: %s\n", k, t, TXT[k][0], TXT[k][1]);
                    for (int i = 0; i < 128; i++) {
                        uint32_t x, y, s;
                        memcpy(&x, &a.v[i], 4); memcpy(&y, &b.v[i], 4); memcpy(&s, &start.v[i], 4);
                        if (x != y) printf("  v[%d]: ref %08X cand %08X (was %08X)\n", i, x, y, s);
                    }
                    for (int i = 0; i < 32; i++)
                        if (a.r[i] != b.r[i]) printf("  r[%d]: ref %08X cand %08X\n", i, a.r[i], b.r[i]);
                }
                bad++;
                break;
            }
        }
    }
    printf("vfpu_diff: %d statements x %d register files: %d mismatched (%d runs differed only in a NaN payload)\n",
           NPAIRS, trials, bad, nan_only);
    return bad != 0;
}
'''


# Moves and bit operations (the forms this test was written for) must match
# bit for bit, NaN payloads included.
STRICT_OPS = ('psp_mtv(', 'psp_mfv(', 'psp_vmmov(', 'psp_vconv(', 'psp_vcst(', 'psp_vi2f(',
              'psp_vcmov(', 'psp_vidt(', 'psp_vimm(', 'psp_vmidt(', 'psp_vmzero(', 'psp_vmone(', 'psp_vcmp(')


def strict(o, n):
    return int(any(k in o for k in STRICT_OPS))


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('old')
    ap.add_argument('new')
    ap.add_argument('outdir')
    ap.add_argument('--trials', type=int, default=200)
    ap.add_argument('--cc', default='cl')
    ap.add_argument('--lib', default=os.path.join(ROOT, 'psprecomp', 'build', 'Release', 'psprecomp.lib'))
    a = ap.parse_args()
    ps = pairs(a.old, a.new)
    os.makedirs(a.outdir, exist_ok=True)
    src = os.path.join(a.outdir, 'vfpu_diff.c')
    with open(src, 'w', encoding='utf-8', newline='\n') as f:
        f.write(PROLOGUE)
        for k, (o, n) in enumerate(ps):
            f.write('static void ref_%d(void) {\n    %s\n}\n' % (k, o))
            f.write('static void cand_%d(void) {\n    %s\n}\n' % (k, n))
        f.write('#define NPAIRS %d\n' % len(ps))
        f.write('static void (*const REF[])(void) = {\n%s\n};\n' % ',\n'.join('    ref_%d' % k for k in range(len(ps))))
        f.write('static void (*const CAND[])(void) = {\n%s\n};\n' % ',\n'.join('    cand_%d' % k for k in range(len(ps))))
        f.write('static const unsigned char STRICT[] = {\n%s\n};\n' % ',\n'.join('    %d' % strict(o, n) for o, n in ps))
        print('vfpu_diff: %d of them compared strictly (moves and bit operations)' % sum(strict(o, n) for o, n in ps))
        f.write('static const char *const TXT[][2] = {\n%s\n};\n' %
                ',\n'.join('    { %s, %s }' % (c_str(o), c_str(n)) for o, n in ps))
        f.write(MAIN)
    print('vfpu_diff: %d statement pairs -> %s' % (len(ps), src))
    gen_dir = os.path.dirname(os.path.abspath(a.new))
    inc = os.path.join(ROOT, 'psprecomp', 'include')
    exe = os.path.join(a.outdir, 'vfpu_diff.exe')
    if a.cc == 'cl':
        cmd = ['cl', '/nologo', '/O1', '/MD', '/w', '/I', gen_dir, '/I', inc, src, a.lib, '/Fe' + exe, '/Fo' + a.outdir + os.sep]
    else:
        cmd = [a.cc, '-O1', '-w', '-I', gen_dir, '-I', inc, src, a.lib, '-lm', '-o', exe]
    subprocess.check_call(cmd)
    sys.exit(subprocess.call([exe, str(a.trials)]))


if __name__ == '__main__':
    main()
