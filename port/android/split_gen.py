"""Split port/gen/recomp_funcs.c into several translation units for clang.

allegrexrecomp writes the game's code as one ~200 MB C file. MSVC compiles it
function by function; clang keeps a whole translation unit in memory while it
optimises and runs out of memory on it (seen with 32 GB). Here the file is cut
at the banners that start each function, into N parts that compile alone:

  - the file-static items (psp_body_*, psp_step_*, psp_orig_*, psp_scc_step and
    the variable psp_scc_next) become external, declared in recomp_split.h;
  - psp_scc_drain, a two-line helper, becomes a static inline in that header;
  - part 0 defines psp_scc_next.

Nothing else changes, so the parts behave exactly as the single file does.

  python split_gen.py <recomp_funcs.c> <out dir> [parts] [hot list] [locals]

A hot list (one PSP address per line, # comments; the 3DS port's
hot_functions.txt) puts those functions in recomp_hot_NN.c instead, so a
build can compile them differently (the 3DS: -O2 with inline memory access).
`locals` also keeps those functions' MIPS registers in C locals
(reg_locals.py); `vlocals` their vector registers as well.

The output is rewritten only when the input (or the hot list, or the mode) is
newer than it, and then only the files whose text changed, so a build
recompiles just those (switching `vlocals`: the hot files).
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reg_locals

BANNER = '/* ---------------------------------------------------------------'
STATIC_DEF = re.compile(r'^static (void psp_(?:body|step|orig)_[0-9A-F]{8}\([^)]*\))')
# external functions defined in the file but declared only there (psp_at_*, the
# label entry points), which other parts may name
EXTERN_DEF = re.compile(r'^(void psp_[a-z]+_[0-9A-F]{8}\([^)]*\))\s*\{')


def write_if_changed(path, text):
    """Write text unless the file already holds it (its time stamp then stays,
    and the build doesn't recompile it). Returns 1 if written."""
    if os.path.exists(path):
        with open(path, 'r', encoding='utf-8', newline='') as f:
            if f.read() == text:
                return 0
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return 1


def main():
    src, out = sys.argv[1], sys.argv[2]
    parts = int(sys.argv[3]) if len(sys.argv) > 3 else 24
    hot_path = sys.argv[4] if len(sys.argv) > 4 and sys.argv[4] else None
    mode = sys.argv[5] if len(sys.argv) > 5 else ''
    locals_on, vlocals = mode in ('locals', 'vlocals'), mode == 'vlocals'
    header = os.path.join(out, 'recomp_split.h')
    stamp = os.path.join(out, 'split_stamp.txt')    # the mode the parts were written with
    head = '/* Generated by port/android/split_gen.py from recomp_funcs.c -- do not edit. */\n'
    newest = max(os.path.getmtime(src), os.path.getmtime(hot_path) if hot_path else 0,
                 os.path.getmtime(reg_locals.__file__), os.path.getmtime(os.path.abspath(__file__)))
    if os.path.exists(stamp) and os.path.getmtime(stamp) >= newest:
        with open(stamp, 'r', encoding='utf-8') as f:
            if f.read() == mode + '\n':
                print('split_gen: up to date')
                return
    hot = set()
    if hot_path:
        with open(hot_path, 'r', encoding='utf-8') as f:
            for l in f:
                l = l.split('#')[0].strip().upper()
                if l:
                    hot.add(l)
    os.makedirs(out, exist_ok=True)
    with open(src, 'r', encoding='utf-8', newline='') as f:
        lines = f.read().split('\n')

    first = next(i for i, l in enumerate(lines) if l.startswith(BANNER))
    preamble, body = lines[:first], lines[first:]
    for l in preamble:                      # what this script knows how to move into the header
        if l.startswith('static ') and not (l.startswith('static uint32_t psp_scc_next;') or
                                            l.startswith('static void psp_scc_step(') or
                                            l.startswith('static void psp_scc_drain(')):
            sys.exit('split_gen: unexpected file-static item in the preamble: ' + l)

    protos = []
    for i, l in enumerate(body):
        if l.startswith('static void psp_scc_step(uint32_t t);'):
            body[i] = ''                    # the forward declaration: in the header now
            continue
        m = STATIC_DEF.match(l)
        if m:
            protos.append(m.group(1) + ';')
            body[i] = l[len('static '):]
        elif EXTERN_DEF.match(l):
            protos.append(EXTERN_DEF.match(l).group(1) + ';')
        elif l.startswith('static void psp_scc_step('):
            body[i] = l[len('static '):]
        elif l.startswith('static ') :
            sys.exit('split_gen: unexpected file-static item: ' + l[:100])

    h = [head, '#ifndef RECOMP_SPLIT_H\n#define RECOMP_SPLIT_H\n#include "recomp_funcs.h"\n\n']
    if os.path.exists(os.path.join(os.path.dirname(src), 'recomp_vfpu.h')):
        h.append('#include "recomp_vfpu.h"   /* the inline VFPU guard, PSP_VFPU_NOPFX (allegrexrecomp emit.c) */\n\n')
    h.append('extern uint32_t psp_scc_next;   /* a pending tail transfer within a tail-call cycle */\n')
    h.append('void psp_scc_step(uint32_t t);\n')
    h.append('static inline void psp_scc_drain(void) {\n'
             '    while (psp_scc_next) { const uint32_t t_ = psp_scc_next; psp_scc_next = 0; psp_scc_step(t_); }\n'
             '}\n\n')
    h.append('\n'.join(protos))
    h.append('\n\n#endif\n')
    written = write_if_changed(header, ''.join(h))

    starts = [i for i, l in enumerate(body) if l.startswith(BANNER)]
    # the hot functions' blocks (banner to the next banner) move out
    hot_blocks = []
    if hot:
        bounds = starts + [len(body)]
        keep = []
        for k in range(len(starts)):
            block = body[bounds[k]:bounds[k + 1]]
            m = re.match(r'^ \* psp_func_([0-9A-F]{8}) ', block[1] if len(block) > 1 else '')
            (hot_blocks if m and m.group(1) in hot else keep).append(block)
        body = [l for block in keep for l in block]
        starts = [i for i, l in enumerate(body) if l.startswith(BANNER)]
    per = max(1, len(starts) // parts)
    cuts = [starts[k] for k in range(0, len(starts), per)][:parts] + [len(body)]
    for p in range(len(cuts) - 1):
        t = ['/* Part %d of recomp_funcs.c (port/android/split_gen.py) -- do not edit. */\n' % p,
             '#include "recomp_split.h"\n\n']
        if p == 0:
            t.append('uint32_t psp_scc_next;\n\n')
        t.append('\n'.join(body[cuts[p]:cuts[p + 1]]))
        t.append('\n')
        written += write_if_changed(os.path.join(out, 'recomp_part_%02d.c' % p), ''.join(t))
    nhot = min(4, len(hot_blocks))
    for p in range(nhot):
        t = ['/* Hot functions of recomp_funcs.c, part %d (port/android/split_gen.py) -- do not edit. */\n' % p,
             '#include "recomp_split.h"\n\n']
        for block in hot_blocks[p::nhot]:
            if locals_on:
                block, _ = reg_locals.transform_lines(block, {int(a, 16) for a in hot}, vlocals)
            t.append('\n'.join(block))
            t.append('\n')
        written += write_if_changed(os.path.join(out, 'recomp_hot_%02d.c' % p), ''.join(t))
    for stale in os.listdir(out):           # parts left over from a run with more parts
        m = re.match(r'recomp_part_(\d+)\.c$', stale)
        if m and int(m.group(1)) >= len(cuts) - 1:
            os.remove(os.path.join(out, stale))
        m = re.match(r'recomp_hot_(\d+)\.c$', stale)
        if m and int(m.group(1)) >= nhot:
            os.remove(os.path.join(out, stale))
    with open(stamp, 'w', encoding='utf-8', newline='\n') as f:
        f.write(mode + '\n')
    print('split_gen: %d functions (%d hot%s), %d prototypes, %d parts; %d files changed' %
          (len(starts) + len(hot_blocks), len(hot_blocks),
           ', registers in locals' + (' (vector ones too)' if vlocals else '') if locals_on else '',
           len(protos), len(cuts) - 1, written))


if __name__ == '__main__':
    main()
